import { Schema } from "effect"
import { Nexus } from "@opencode/schema/nexus"
import { NexusPreset } from "@opencode/schema/nexus-preset"
import { NexusBot } from "@opencode/schema/nexus-bot"
import { NexusAcp } from "@opencode/schema/nexus-acp"

import { NexusSettings } from "@opencode/schema/nexus-settings"

const Rule = Schema.Union([
  Schema.Struct({ kind: Schema.Literal("once"), run_at: Schema.String }),
  Schema.Struct({ kind: Schema.Literal("interval"), starts_at: Schema.String, every_seconds: Schema.Int }),
  Schema.Struct({ kind: Schema.Literal("daily"), local_time: Schema.String, time_zone: Schema.String }),
])
export const NexusCommand = Schema.Union([
  Schema.Struct({ action: Schema.Literal("workspace.list") }),
  Schema.Struct({
    action: Schema.Literal("workspace.create"),
    name: Schema.NonEmptyString,
    key: Schema.NonEmptyString,
  }),
  Schema.Struct({ action: Schema.Literal("workspace.use"), workspace: Schema.NonEmptyString }),
  Schema.Struct({ action: Schema.Literal("settings.read") }),
  Schema.Struct({ action: Schema.Literal("settings.update"), patch: NexusSettings.Patch }),
  Schema.Struct({
    action: Schema.Literal("connection.import"),
    origin: Schema.String,
    model: Schema.String,
    workspace: Schema.String,
    directory: Schema.String,
    access_token: Schema.NonEmptyString,
    executor_access_token: Schema.NonEmptyString,
  }),
  ...NexusPreset.Command.members,
  ...NexusBot.Command.members,
  ...NexusAcp.Command.members,
  Schema.Struct({
    action: Schema.Literal("application.accepted"),
    workspace: Schema.String,
    conversation: Schema.String,
    input: Schema.String,
    text: Schema.String,
    model: Schema.optional(Schema.String),
    replayed: Schema.Boolean,
  }),
  Schema.Struct({ action: Schema.Literal("application.skills") }),
  Schema.Struct({
    action: Schema.Literal("application.memory"),
    workspace: Schema.optional(Schema.NonEmptyString),
    conversation: Schema.NonEmptyString,
    speaker: Schema.optional(Schema.NonEmptyString),
    command: Schema.String,
    format: Schema.optional(Schema.Literals(["text", "json"])),
  }),
  Schema.Struct({
    action: Schema.Literal("application.approve"),
    workspace: Schema.NonEmptyString,
    conversation: Schema.NonEmptyString,
    run: Schema.NonEmptyString,
    task: Schema.NonEmptyString,
    always: Schema.optional(Schema.Boolean),
  }),
  Schema.Struct({ action: Schema.Literal("persona.read") }),
  Schema.Struct({ action: Schema.Literal("persona.reset") }),
  Schema.Struct({ action: Schema.Literal("persona.write"), content: Schema.String }),
  Schema.Struct({
    action: Schema.Literal("application.open"),
    workspace: Schema.optional(Schema.NonEmptyString),
    key: Schema.NonEmptyString,
    model: Schema.optional(Schema.NonEmptyString),
    title: Schema.optional(Schema.String),
    runner: Schema.optional(Schema.NullOr(Schema.String)),
    environment: Schema.optional(Nexus.EnvironmentRoots),
  }),
  Schema.Struct({
    action: Schema.Literals(["application.prepare", "application.submit"]),
    addressed: Schema.optional(Schema.Boolean),
    answering_user_public_id: Schema.optional(Schema.String),
    key: Schema.NonEmptyString,
    workspace: Schema.String,
    conversation: Schema.String,
    text: Schema.String,
    attachments: Schema.optional(Schema.Array(Schema.String)),
    until: Schema.optional(
      Schema.Struct({
        command: Schema.NonEmptyString,
        attempts: Schema.optional(Schema.Int.check(Schema.isBetween({ minimum: 1, maximum: 20 }))),
        directory: Schema.optional(Schema.String),
      }),
    ),
    model: Schema.optional(Schema.NullOr(Schema.String)),
    preset: Schema.optional(Schema.String),
    approval: Schema.optional(Schema.Literals(["bypass", "ask", "rules"])),
    target: Schema.optional(Schema.String),
    instructions: Schema.optional(Schema.String),
    delivery: Schema.optional(Schema.Literals(["queue", "steer", "steer_now"])),
  }),
  Schema.Struct({
    action: Schema.Literal("application.result"),
    workspace: Schema.String,
    conversation: Schema.String,
    input: Schema.String,
  }),
  Schema.Struct({ action: Schema.Literal("extension.list") }),
  Schema.Struct({
    action: Schema.Literal("extension.asset"),
    id: Schema.NonEmptyString,
    version: Schema.NonEmptyString,
    path: Schema.NonEmptyString,
  }),
  Schema.Struct({ action: Schema.Literal("application.defaults") }),
  Schema.Struct({
    action: Schema.Literal("application.operation"),
    workspace: Schema.optional(Schema.NonEmptyString),
    operation: Schema.Json,
  }),
  Schema.Struct({
    action: Schema.Literal("platform.request"),
    principal: Schema.NonEmptyString,
    path: Schema.NonEmptyString,
    method: Schema.Literals(["GET", "POST", "PUT", "PATCH", "DELETE"]),
    body: Schema.optional(Schema.Json),
    key: Schema.optional(Schema.String),
  }),
  Schema.Struct({ action: Schema.Literal("login.device") }),
  Schema.Struct({ action: Schema.Literal("extension.configure"), change: Nexus.ExtensionChange }),
  Schema.Struct({
    action: Schema.Literal("extension.call"),
    name: Schema.NonEmptyString,
    input: Schema.Json,
  }),
  Schema.Struct({
    action: Schema.Literal("schedule.list"),
    workspace: Schema.optional(Schema.NonEmptyString),
    conversation: Schema.optional(Schema.NonEmptyString),
    after: Schema.optional(Schema.String),
  }),
  Schema.Struct({ action: Schema.Literal("memory.collections"), workspace: Schema.optional(Schema.NonEmptyString) }),
  Schema.Struct({
    action: Schema.Literal("schedule.create"),
    model: Schema.optional(Schema.NonEmptyString),
    workspace: Schema.optional(Schema.NonEmptyString),
    approval: Schema.optional(Schema.Literals(["ask", "rules", "bypass"])),
    conversation: Schema.String,
    key: Schema.NonEmptyString,
    prompt: Schema.String,
    name: Schema.optional(Schema.String),
    rule: Rule,
  }),
  Schema.Struct({
    action: Schema.Literals(["schedule.pause", "schedule.resume", "schedule.cancel", "schedule.run", "schedule.read"]),
    workspace: Schema.optional(Schema.NonEmptyString),
    conversation: Schema.String,
    id: Schema.String,
  }),
  Schema.Struct({
    action: Schema.Literal("schedule.executions"),
    workspace: Schema.optional(Schema.NonEmptyString),
    conversation: Schema.String,
    id: Schema.String,
    after: Schema.optional(Schema.String),
  }),
  Schema.Struct({
    action: Schema.Literal("schedule.update"),
    model: Schema.optional(Schema.NonEmptyString),
    workspace: Schema.optional(Schema.NonEmptyString),
    conversation: Schema.String,
    id: Schema.String,
    version: Schema.Int,
    name: Schema.optional(Schema.String),
    approval: Schema.optional(Schema.Literals(["ask", "rules", "bypass"])),
    prompt: Schema.optional(Schema.String),
    rule: Schema.optional(Rule),
  }),
  Schema.Struct({
    action: Schema.Literal("memory.create"),
    name: Schema.String,
    workspace: Schema.optional(Schema.NonEmptyString),
  }),
  Schema.Struct({
    action: Schema.Literals(["memory.list", "memory.read", "memory.grep"]),
    workspace: Schema.optional(Schema.NonEmptyString),
    collection: Schema.String,
    path: Schema.optional(Schema.String),
    pattern: Schema.optional(Schema.String),
  }),
  Schema.Struct({
    action: Schema.Literal("memory.write"),
    workspace: Schema.optional(Schema.NonEmptyString),
    collection: Schema.String,
    path: Schema.String,
    content: Schema.String,
    id: Schema.NullOr(Schema.String),
    version: Schema.NullOr(Schema.Int),
  }),
  Schema.Struct({
    action: Schema.Literal("memory.delete"),
    workspace: Schema.optional(Schema.NonEmptyString),
    collection: Schema.String,
    path: Schema.String,
    id: Schema.String,
    version: Schema.Int,
  }),
  Schema.Struct({
    action: Schema.Literals(["memory.archive", "memory.restore"]),
    workspace: Schema.optional(Schema.NonEmptyString),
    collection: Schema.String,
    version: Schema.Int,
  }),
])

export const NexusOperator = Schema.Struct({
  workspace: Schema.String,
  conversation: Schema.String,
  runner: Schema.String,
  receipt: Schema.NonEmptyString,
  operation: Schema.Union([
    Schema.Struct({ tool: Schema.Literal("files_bytes"), path: Schema.String }),
    Schema.Struct({ tool: Schema.Literal("checkpoint_restore"), run: Schema.String, task: Schema.String }),
  ]),
})
